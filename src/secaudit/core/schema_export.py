"""JSON Schema of the normalized Audit (findings.json), exported to docs/schema/.

`python -m secaudit.core.schema_export` rewrites the committed file; tests/test_schema_export.py
fails when the committed schema and the models disagree, so a model change without a schema update
(and a version bump when the change is breaking) cannot be merged unnoticed.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from secaudit.core.models import SCHEMA_VERSION, Audit

SCHEMA_FILENAME = "audit.schema.json"
DEFAULT_DIR = Path(__file__).resolve().parents[3] / "docs" / "schema"


def audit_schema() -> dict:
    schema = Audit.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$comment"] = (
        f"secaudit findings.json, schema_version {SCHEMA_VERSION}. Generated by "
        "`python -m secaudit.core.schema_export`; do not edit by hand."
    )
    return schema


def render_schema() -> str:
    return json.dumps(audit_schema(), indent=2, sort_keys=True) + "\n"


def write_schema(directory: Path = DEFAULT_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / SCHEMA_FILENAME
    target.write_text(render_schema(), encoding="utf-8", newline="\n")
    return target


if __name__ == "__main__":
    print(f"wrote {write_schema(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIR)}")
