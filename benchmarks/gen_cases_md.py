"""Generate benchmarks/CASES.md from benchmarks/expected_findings_expansion.yaml.

The output is deterministic and LF-only, and has no timestamp, so a test can pin the committed file
to the generator.

Usage: python benchmarks/gen_cases_md.py [--check]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

BENCH_DIR = Path(__file__).resolve().parent
EXPANSION = BENCH_DIR / "expected_findings_expansion.yaml"
OUTPUT = BENCH_DIR / "CASES.md"

KIND_ORDER = ("positive", "negative", "injection_bait", "masking_probe", "unscored")
HEADER = (
    "| ID | Kind | Title | File:lines | CWE | Exposure | "
    "Prior detectability (sast / secrets / sca) |\n"
    "|---|---|---|---|---|---|---|\n"
)


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|")


def _lines(case: dict) -> str:
    start, end = case["line_start"], case["line_end"]
    return f"{start}" if start == end else f"{start}-{end}"


def _prior(case: dict) -> str:
    prior = case.get("prior_detectability")
    return " / ".join(prior[k] for k in ("sast", "secrets", "sca")) if prior else "-"


def _sort_key(case: dict) -> tuple[int, int, str]:
    number = re.search(r"\d+", str(case["id"]))
    return KIND_ORDER.index(case["kind"]), int(number.group()) if number else 0, str(case["id"])


def render(doc: dict) -> str:
    """The catalogue text for a parsed expansion file."""
    cases = doc["cases"]
    parts = [
        "# Benchmark case catalogue (Phase 2C expansion)\n\n"
        "Generated by `benchmarks/gen_cases_md.py` from "
        "`benchmarks/expected_findings_expansion.yaml`. Do not edit by hand.\n\n"
        "The `Prior detectability` column is the prediction registered before any scanner ran on "
        "these targets. The original cases of `vuln_python_app` are in "
        "`benchmarks/expected_findings.yaml`. `unscored` cases are excluded from all metrics; "
        "`benchmarks/LABEL_REVIEW.md` lists the corrections made before any scan.\n"
    ]
    for target in sorted({case["target"] for case in cases}):
        rows = sorted((c for c in cases if c["target"] == target), key=_sort_key)
        table = "".join(
            f"| {c['id']} | {c['kind']} | {_cell(c['title'])} | "
            f"`{c['file']}:{_lines(c)}` | {c.get('cwe') or '-'} | "
            f"{c['context']['exposure']} | {_prior(c)} |\n"
            for c in rows
        )
        parts.append(f"\n## {target}\n\n{HEADER}{table}")
    return "".join(parts)


def generate(source: Path = EXPANSION) -> str:
    return render(yaml.safe_load(source.read_text(encoding="utf-8")))


def main(argv: list[str]) -> int:
    text = generate()
    if "--check" in argv:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != text.encode("utf-8"):
            print(f"{OUTPUT.name} is out of date: run benchmarks/gen_cases_md.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
